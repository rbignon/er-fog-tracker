function handleSearch(query) {
    if (!query) {
        searchDropdown.classList.remove('visible');
        searchDropdown.innerHTML = '';
        State.emit('searchCleared');
        return;
    }

    const graphData = State.getGraphData();
    if (!graphData) return;

    // Find matching nodes (search on display name, fallback to id)
    const matching = graphData.nodes.filter(n => (n.name || n.id).toLowerCase().includes(query.toLowerCase()));

    State.emit('searchMatched', { matchingIds: new Set(matching.map(n => n.id)) });

    // Show dropdown with undiscovered matches in exploration mode (not for viewers)
    if (State.isExplorationMode() && !State.isViewerMode()) {
        const explorationState = State.getExplorationState();
        const undiscoveredMatches = matching.filter(n => !explorationState.discovered.has(n.id));

        if (undiscoveredMatches.length > 0) {
            let html = '';
            undiscoveredMatches.slice(0, 8).forEach(n => {
                html += `
                    <div class="search-result">
                        <div>
                            <span class="search-result-name">${n.name || n.id}</span>
                            <span class="search-result-status">(not discovered)</span>
                        </div>
                        <button class="search-result-btn" data-node-id="${n.id}">🎯 I've reached</button>
                    </div>
                `;
            });
            if (undiscoveredMatches.length > 8) {
                html += `<div class="search-result"><span class="search-result-status">... and ${undiscoveredMatches.length - 8} more</span></div>`;
            }
            searchDropdown.innerHTML = html;
            searchDropdown.classList.add('visible');

            // Add click handlers
            searchDropdown.querySelectorAll('.search-result-btn').forEach(btn => {
                btn.addEventListener('click', function () {
                    const nodeId = this.getAttribute('data-node-id');
                    Exploration.discoverPathTo(nodeId);
                    searchInput.value = '';
                    searchDropdown.classList.remove('visible');
                    searchDropdown.innerHTML = '';
                    State.emit('searchCleared');
                });
            });
        } else {
            searchDropdown.classList.remove('visible');
            searchDropdown.innerHTML = '';
        }
    }
}

