function showError(msg) {
    errorMessage.innerHTML = msg;
}

function clearError() {
    errorMessage.innerHTML = '';
}

// Process spoiler log text (common logic for files and demo)
async function processSpoilerLogText(text) {
    // Quick client-side validation for better UX
    const hasFogPatterns = text.includes('Preexisting:');
    const hasScaling = text.includes('scaling:');

    if (!hasFogPatterns && !hasScaling) {
        if (text.includes('-- Item preset')) {
            throw new Error(
                'This appears to be an <strong>Item Randomizer</strong> spoiler log, not a Fog Randomizer log.<br><br>Please load a spoiler log from the <strong>Fog Gate Randomizer</strong> mod.'
            );
        }
        if (text.includes('-- Enemy preset')) {
            throw new Error(
                'This appears to be an <strong>Enemy Randomizer</strong> spoiler log, not a Fog Randomizer log.<br><br>Please load a spoiler log from the <strong>Fog Gate Randomizer</strong> mod.'
            );
        }
        throw new Error(
            "This does not appear to be a valid Fog Randomizer spoiler log.<br><br>Make sure you're loading the spoiler log generated by the <strong>Fog Gate Randomizer</strong> mod."
        );
    }

    // Parse via API
    const apiData = await parseSpoilerLog(text);

    // Set starting zone before loading exploration state
    if (apiData.starting_zone_id) {
        State.setStartNodeId(apiData.starting_zone_id);
    }

    // Transform API response to frontend format
    const parsedData = {
        nodes: transformZonesFromApi(apiData.zones),
        links: transformLinksFromApi(apiData.zone_links),
        metadata: {
            seed: apiData.seed,
            startingZoneId: apiData.starting_zone_id,
        },
    };

    if (parsedData.nodes.length === 0) {
        throw new Error('No areas found in the log file.');
    }

    // Show main UI
    uploadScreen.classList.add('hidden');
    mainUI.classList.add('visible');

    // Reset search
    searchInput.value = '';

    // Set seed BEFORE render so exploration state can be loaded
    const newSeed = parsedData.metadata.seed;
    State.setSeed(newSeed);

    // Check if we already have saved graph data for this seed (preserves UUIDs)
    const existingGraphData = State.loadGraphFromStorage(newSeed);
    const graphData = existingGraphData || parsedData;

    // Store graph data
    State.setGraphData(graphData);

    // Save to localStorage only if this is a new seed
    if (!existingGraphData) {
        State.saveGraphToStorage();
    }

    // Update URL with seed parameter in offline mode (enables refresh/bookmark)
    if (State.getBackendMode() === 'offline') {
        const newUrl = `/?offline=true&seed=${newSeed}`;
        history.replaceState(null, '', newUrl);
    }

    // Load exploration state BEFORE render (if saved), or initialize
    if (State.isExplorationMode()) {
        if (!Exploration.loadExplorationState(newSeed)) {
            Exploration.initExplorationState();
        }
    }

    // Trigger render
    State.emit('graphNeedsRender', { preservePositions: false });

    // Update UI controls based on current mode
    updateModeButtons();
}

/**
 * Load a saved offline game by seed.
 * @param {string} seed - The seed to load
 * @returns {boolean} True if game was loaded, false otherwise
 */
export function loadOfflineGame(seed) {
    const graphData = State.loadGraphFromStorage(seed);
    if (!graphData) return false;

    // Show main UI
    uploadScreen.classList.add('hidden');
    mainUI.classList.add('visible');

    // Reset search
    searchInput.value = '';

    // Set seed and graph data
    State.setSeed(seed);
    State.setGraphData(graphData);

    // Load exploration state
    if (State.isExplorationMode()) {
        if (!Exploration.loadExplorationState(seed)) {
            Exploration.initExplorationState();
        }
    }

    // Trigger render
    State.emit('graphNeedsRender', { preservePositions: false });

    // Update UI controls
    updateModeButtons();

    return true;
}

function handleFile(file) {
    clearError();

    if (!file) {
        showError('No file selected');
        return;
    }

    const reader = new FileReader();

    reader.onload = async e => {
        try {
            await processSpoilerLogText(e.target.result);
        } catch (err) {
            console.error(err);
            showError(err.message || `Error parsing the log file: ${err}`);
        }
    };

    reader.onerror = () => {
        showError('Error reading the file.');
    };

    reader.readAsText(file);
}

async function loadDemoData() {
    clearError();

    try {
        const response = await fetch('data/demo_log.txt');
        if (!response.ok) {
            throw new Error('Demo file not found');
        }
        const text = await response.text();
        await processSpoilerLogText(text);
    } catch (err) {
        console.error(err);
        showError(`Error loading demo: ${err.message}`);
    }
}

