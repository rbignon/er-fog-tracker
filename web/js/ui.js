export function initUI() {
    // File upload
    dropZone.addEventListener('click', () => fileInput.click());

    fileInput.addEventListener('change', e => {
        handleFile(e.target.files[0]);
    });

    dropZone.addEventListener('dragover', e => {
        e.preventDefault();
        dropZone.classList.add('dragover');
    });

    dropZone.addEventListener('dragleave', e => {
        e.preventDefault();
        dropZone.classList.remove('dragover');
    });

    dropZone.addEventListener('drop', e => {
        e.preventDefault();
        dropZone.classList.remove('dragover');
        handleFile(e.dataTransfer.files[0]);
    });

    // New file button
    newFileBtn.addEventListener('click', () => {
        mainUI.classList.remove('visible');
        uploadScreen.classList.remove('hidden');
        fileInput.value = '';
        clearError();

        const sim = State.getSimulation();
        if (sim) sim.stop();
    });

    // Demo button
    const demoBtn = document.getElementById('demo-btn');
    if (demoBtn) {
        demoBtn.addEventListener('click', loadDemoData);
    }

    // Search
    searchInput.addEventListener('input', e => {
        handleSearch(e.target.value);
        updateSearchClearButton();
    });

    // Search clear button
    if (searchClearBtn) {
        searchClearBtn.addEventListener('click', () => {
            searchInput.value = '';
            searchInput.focus();
            searchDropdown.classList.remove('visible');
            searchDropdown.innerHTML = '';
            updateSearchClearButton();
            State.emit('searchCleared');
        });
    }

    document.addEventListener('click', e => {
        if (!e.target.closest('#search-container')) {
            searchDropdown.classList.remove('visible');
        }
    });

    // Mode buttons
    const modeSpoilerBtn = document.getElementById('mode-spoiler');
    const modeExplorerBtn = document.getElementById('mode-explorer');

    modeSpoilerBtn.addEventListener('click', switchToSpoilerMode);
    modeExplorerBtn.addEventListener('click', switchToExplorerMode);

    // Reset button
    const resetBtn = document.getElementById('reset-exploration-btn');
    resetBtn.addEventListener('click', () => {
        if (confirm('Reset your exploration progress? All discovered areas and tags will be lost.')) {
            Exploration.resetExplorationState();
        }
    });

    // Frontier checkbox
    const frontierCheckbox = document.getElementById('show-frontier-checkbox');
    if (frontierCheckbox) {
        frontierCheckbox.addEventListener('change', () => {
            onFrontierCheckboxChange(frontierCheckbox.checked);
        });
    }

    // Path from start checkbox
    const pathCheckbox = document.getElementById('show-path-from-start');
    if (pathCheckbox) {
        pathCheckbox.addEventListener('change', () => {
            State.emit('pathFromStartChanged', pathCheckbox.checked);
        });
    }

    // Helper to clear search
    function clearSearch() {
        searchInput.value = '';
        searchInput.blur();
        searchDropdown.classList.remove('visible');
        searchDropdown.innerHTML = '';
        updateSearchClearButton();
        State.emit('searchCleared');
    }

    // Keyboard shortcuts
    document.addEventListener('keydown', e => {
        // Escape: clear search if active, otherwise close tooltip
        if (e.key === 'Escape') {
            // If in search input, clear and blur
            if (e.target === searchInput) {
                clearSearch();
                e.preventDefault();
                return;
            }

            // Ignore if typing in other input fields
            if (e.target.tagName === 'INPUT' || e.target.tagName === 'TEXTAREA') return;

            // If search has text, clear it first
            if (searchInput.value.trim()) {
                clearSearch();
                e.preventDefault();
                return;
            }

            // Otherwise close tooltip
            const closeBtn = document.querySelector('#tooltip.visible .close-btn');
            if (closeBtn) {
                closeBtn.click();
                e.preventDefault();
            }
            return;
        }

        // Ignore other keys if typing in an input field
        if (e.target.tagName === 'INPUT' || e.target.tagName === 'TEXTAREA') return;

        // Ignore if no graph loaded
        if (!State.getGraphData()) return;

        const key = e.key.toLowerCase();

        // D: Discover selected placeholder
        if (key === 'd') {
            const discoverBtn = document.querySelector('#tooltip.visible .discover-btn');
            if (discoverBtn) {
                discoverBtn.click();
                e.preventDefault();
            }
            return;
        }

        // U: Undiscover selected node
        if (key === 'u') {
            const undiscoverBtn = document.querySelector('#tooltip.visible .undiscover-btn');
            if (undiscoverBtn) {
                undiscoverBtn.click();
                e.preventDefault();
            }
            return;
        }

        // F: Toggle frontier highlight
        if (key === 'f') {
            if (!State.isExplorationMode()) return;

            const frontierCheckbox = document.getElementById('show-frontier-checkbox');
            if (frontierCheckbox) {
                frontierCheckbox.checked = !frontierCheckbox.checked;
                onFrontierCheckboxChange(frontierCheckbox.checked);
                e.preventDefault();
            }
            return;
        }

        // P: Toggle path from start
        if (key === 'p') {
            const pathCheckbox = document.getElementById('show-path-from-start');
            if (pathCheckbox) {
                pathCheckbox.checked = !pathCheckbox.checked;
                State.emit('pathFromStartChanged', pathCheckbox.checked);
                e.preventDefault();
            }
            return;
        }
    });

    // Window resize
    let resizeTimeout;
    window.addEventListener('resize', () => {
        if (State.getGraphData() && mainUI.classList.contains('visible')) {
            clearTimeout(resizeTimeout);
            resizeTimeout = setTimeout(() => {
                State.saveAllNodePositions();
                State.emit('graphNeedsRender', { preservePositions: true });
            }, 150);
        }
    });

    // Subscribe to state events
    State.subscribe('explorationReset', () => {
        State.emit('graphNeedsRender', { preservePositions: false });
    });

    // Re-apply frontier highlight after graph render if it's active AND nothing is selected
    // Overlay viewers get highlights from host, everyone else calculates locally
    State.subscribe('graphRenderCompleted', () => {
        if (State.isFrontierHighlightActive() && !State.getSelectedNodeId() && !State.isOverlayMode()) {
            highlightFrontier();
        }
    });

    // Re-apply frontier highlight when selection is cleared
    State.subscribe('restoreFrontierHighlight', () => {
        if (State.isFrontierHighlightActive()) {
            if (State.isOverlayMode()) {
                // Overlay viewer: restore host's visual state (don't recalculate)
                restoreLastVisualState();
            } else {
                // Host, interactive viewer, or not connected: recalculate locally
                highlightFrontier();
            }
        }
    });

    // Update UI based on frontier state changes
    State.subscribe('frontierHighlightChanged', active => {
        const frontierCheckbox = document.getElementById('show-frontier-checkbox');
        if (frontierCheckbox) {
            frontierCheckbox.checked = active;
        }

        // Overlay viewers receive visual classes from host via applyVisualClasses()
        // Everyone else (host, interactive viewer, not connected) calculates locally
        if (!State.isOverlayMode()) {
            if (active) {
                highlightFrontier();
            } else {
                clearFrontierHighlight();
            }
        }
    });
}

